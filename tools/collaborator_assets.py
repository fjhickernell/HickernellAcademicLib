#!/usr/bin/env python3
"""Refresh explicitly selected portraits from iCloud, or check publishing copies.

Names come from this pinned library's master catalog. Refresh is deliberate;
check is read-only and needs no iCloud access, so it also works in public CI.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import os
import re
from pathlib import Path

import yaml

LIBRARY = Path(__file__).resolve().parents[1]
MASTER = LIBRARY / "classlib/quarto/metadata/hickernell-collaborators.yml"
PHOTO_ROOT = Path.home() / "Library/Mobile Documents/com~apple~CloudDocs/Collaborator Headshots"
ID_PATTERN = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")


def load_yaml(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError(f"Expected schema_version: 1 in {path}")
    return data


def project_path(root: Path, value: str) -> Path:
    if not isinstance(value, str) or not value:
        raise ValueError("A nonempty project-relative output path is required")
    path = (root / value).resolve()
    if not path.is_relative_to(root) or path == root:
        raise ValueError(f"Output path must stay inside the consumer: {value}")
    return path


def ids(value: object) -> list[str]:
    if not isinstance(value, list) or not all(
        isinstance(item, str) and ID_PATTERN.fullmatch(item) for item in value
    ):
        raise ValueError("Collaborators must be an explicit list of stable IDs")
    if len(set(value)) != len(value):
        raise ValueError("A gallery or extra_ids list contains duplicate people")
    return value


def selection(config: dict, root: Path, master: dict) -> tuple[list[str], dict]:
    people = list(ids(config.get("extra_ids", [])))
    galleries = config.get("galleries", {})
    if not isinstance(galleries, dict):
        raise ValueError("galleries must be a mapping")
    outputs = set()
    for gallery in galleries.values():
        if not isinstance(gallery, dict):
            raise ValueError("Each gallery must be a mapping")
        people.extend(ids(gallery.get("ids")))
        output = project_path(root, gallery["output"])
        if output in outputs:
            raise ValueError("Gallery output paths must be distinct")
        outputs.add(output)
        width = gallery.get("portrait_width", 135)
        columns = gallery.get("columns")
        if type(width) is not int or width <= 0:
            raise ValueError("portrait_width must be a positive integer")
        if columns is not None and (type(columns) is not int or columns <= 0):
            raise ValueError("columns must be a positive integer when supplied")
        if not isinstance(gallery.get("image_prefix"), str):
            raise ValueError("Each gallery needs an image_prefix for its slide")
    selected = list(dict.fromkeys(people))
    if not selected:
        raise ValueError("Select at least one collaborator")
    for person in selected:
        name = master.get(person, {}).get("name")
        if not isinstance(name, str) or not name.strip():
            raise ValueError(f"Unknown ID or missing name in the master catalog: {person}")
    return selected, galleries


def render_gallery(gallery: dict, people: dict) -> str:
    lines = ["<!-- Generated by classlib/tools/collaborator_assets.py; edit the selection, not this file -->"]
    columns = gallery.get("columns")
    if columns:
        lines.append(f'<div class="collab-grid" style="grid-template-columns: repeat({columns}, minmax(0, 1fr));">')
    prefix = gallery["image_prefix"].rstrip("/")
    width = gallery.get("portrait_width", 135)
    for person in gallery["ids"]:
        entry = people[person]
        name = html.escape(entry["name"], quote=True)
        image = html.escape(f'{prefix}/{entry["file"]}', quote=True)
        lines.extend([
            '<div class="collab-card">',
            f'<img src="{image}" alt="{name}" style="width:{width}px;">',
            f'<div class="collab-caption">{name}</div>',
            '</div>',
        ])
    if columns:
        lines.append('</div>')
    return "\n".join(lines) + "\n"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def photo_filename(entry: dict) -> str:
    name = entry.get("file")
    if not isinstance(name, str) or Path(name).name != name:
        raise ValueError("Portrait filenames must not contain directories")
    if Path(name).suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}:
        raise ValueError(f"Unsupported portrait format: {name}")
    return name


def write_changed(path: Path, data: bytes) -> None:
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def run(config_path: Path, project: Path, master_path: Path = MASTER,
        photo_root: Path | None = None, refresh: bool = False) -> dict:
    project = project.resolve()
    config = load_yaml(config_path)
    master = load_yaml(master_path)["collaborators"]
    selected, galleries = selection(config, project, master)
    destination = project_path(project, config["photo_directory"])
    manifest_path = project_path(project, config["manifest"])
    files = {}
    if refresh:
        if photo_root is None:
            raise ValueError("Refresh needs the iCloud headshot folder")
        archive = load_yaml(photo_root / "catalog.yml")["headshots"]
        sources = {}
        for entry in archive:
            person = entry["id"]
            if person in sources:
                raise ValueError(f"Duplicate ID in the photo archive: {person}")
            sources[person] = entry
        people = {}
        # Validate every source before changing any publishing copy.
        for person in selected:
            if person not in sources:
                raise ValueError(f"No iCloud portrait catalog entry for {person}")
            entry = sources[person]
            filename = photo_filename(entry)
            data = (photo_root / filename).read_bytes()
            if digest(data) != entry["sha256"]:
                raise ValueError(f"iCloud portrait hash mismatch: {person}")
            people[person] = {"name": master[person]["name"], "file": filename,
                              "sha256": digest(data)}
            target = destination / filename
            if target in files and files[target] != data:
                raise ValueError(f"Different portraits use the same filename: {filename}")
            files[target] = data
        manifest = {"schema_version": 1, "headshots": people}
    else:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest.get("schema_version") != 1:
            raise ValueError("Unsupported publishing manifest schema")
        people = manifest["headshots"]
        if set(people) != set(selected):
            raise ValueError("Selection changed; run --refresh from the iCloud archive")
        for person in selected:
            entry = people[person]
            filename = photo_filename(entry)
            if entry["name"] != master[person]["name"]:
                raise ValueError(f"Name changed in the master catalog; refresh {person}")
            if digest((destination / filename).read_bytes()) != entry["sha256"]:
                raise ValueError(f"Publishing copy hash mismatch: {person}")
    if manifest_path in files:
        raise ValueError("The manifest path collides with a portrait")
    files[manifest_path] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()
    for gallery in galleries.values():
        output = project_path(project, gallery["output"])
        if output in files:
            raise ValueError("A gallery output collides with another generated file")
        files[output] = render_gallery(gallery, people).encode()
    if refresh:
        for target, data in files.items():
            write_changed(target, data)
    else:
        for target, data in files.items():
            if target.read_bytes() != data:
                raise ValueError(f"Generated file is stale; run --refresh: {target}")
    return {"portraits": len(selected), "galleries": len(galleries),
            "mode": "refreshed" if refresh else "checked"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("selection", type=Path)
    parser.add_argument("--project", type=Path, default=Path.cwd())
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--refresh", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--photo-root", type=Path)
    args = parser.parse_args()
    source = args.photo_root
    if args.refresh and source is None:
        source = Path(os.environ.get("HICKERNELL_HEADSHOT_DIR", str(PHOTO_ROOT)))
    if source is not None:
        source = source.expanduser()
    try:
        result = run(args.selection, args.project, photo_root=source, refresh=args.refresh)
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError) as error:
        parser.exit(1, f"Collaborator assets: {error}\n")
    gallery_word = "gallery" if result["galleries"] == 1 else "galleries"
    print(f'{result["mode"].capitalize()} {result["portraits"]} selected portraits and {result["galleries"]} {gallery_word}')


if __name__ == "__main__":
    main()
